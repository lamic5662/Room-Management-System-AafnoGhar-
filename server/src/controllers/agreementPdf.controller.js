import PDFDocument from "pdfkit";
import fs from "fs";
import path from "path";
import Agreement from "../models/Agreement.js";
import { drawStamp } from "../utils/pdfStamp.js";

const generateAgreementPdf = async (req, res) => {
  try {
    const agreementId = req.params.id;

    const agreement = await Agreement.findById(agreementId)
      .populate("tenant", "fullName email phone")
      .populate("owner", "fullName email phone")
      .populate("room", "title location monthlyRent");

    if (!agreement) return res.status(404).json({ message: "Agreement not found" });

    const uid = String(req.user._id);
    const isOwner = String(agreement.owner?._id) === uid;
    const isTenant = String(agreement.tenant?._id) === uid;
    const isAdmin = req.user.role === "admin";

    if (!isOwner && !isTenant && !isAdmin) {
      return res.status(403).json({ message: "Forbidden" });
    }

    const doc = new PDFDocument({ size: "A4", margin: 50 });

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader("Content-Disposition", `attachment; filename="agreement-${agreementId}.pdf"`);

    doc.pipe(res);

    doc.fontSize(20).text("AafnoGhar Rent Agreement", { align: "center" });
    doc.moveDown(0.5);
    doc.fontSize(10).fillColor("#6b7280").text(`Agreement ID: ${agreementId}`, { align: "center" });
    doc.fillColor("#000000");
    doc.moveDown(1);

    doc.fontSize(14).text("Room Details", { underline: true });
    doc.moveDown(0.4);
    doc.fontSize(11);
    doc.text(`Title: ${agreement.room?.title || "-"}`);
    doc.text(`Location: ${agreement.room?.location || "-"}`);
    doc.text(`Monthly Rent: NPR ${agreement.monthlyRent ?? agreement.room?.monthlyRent ?? "-"}`);
    doc.text(`Security Deposit: NPR ${agreement.securityDeposit ?? "-"}`);
    doc.moveDown(1);

    doc.fontSize(14).text("Parties", { underline: true });
    doc.moveDown(0.4);
    doc.fontSize(11);
    doc.text(`Owner: ${agreement.owner?.fullName || "-"}`);
    doc.text(`Owner Email: ${agreement.owner?.email || "-"}`);
    doc.text(`Owner Phone: ${agreement.owner?.phone || "-"}`);
    doc.moveDown(0.6);
    doc.text(`Tenant: ${agreement.tenant?.fullName || "-"}`);
    doc.text(`Tenant Email: ${agreement.tenant?.email || "-"}`);
    doc.text(`Tenant Phone: ${agreement.tenant?.phone || "-"}`);
    doc.moveDown(1);

    doc.fontSize(14).text("Agreement Terms", { underline: true });
    doc.moveDown(0.4);
    doc.fontSize(11);

    const start = agreement.startDate ? new Date(agreement.startDate).toDateString() : "-";
    const end = agreement.endDate ? new Date(agreement.endDate).toDateString() : "-";

    doc.text(`Start Date: ${start}`);
    doc.text(`End Date: ${end}`);
    doc.text(`Status: ${agreement.status || "-"}`);
    doc.moveDown(1);

    doc.fontSize(14).text("Terms & Conditions (Summary)", { underline: true });
    doc.moveDown(0.4);
    doc.fontSize(11);
    doc.text(
      "1) Tenant agrees to pay rent on time each month.\n" +
      "2) Tenant must follow owner rules and keep room in good condition.\n" +
      "3) Security deposit will be refundable after deductions (if any).\n" +
      "4) Complaints and maintenance issues should be reported properly.\n" +
      "5) Agreement ends on end date or after exit settlement.\n",
      { lineGap: 4 }
    );

    doc.moveDown(1);

    doc.fontSize(14).text("Signatures", { underline: true });
    doc.moveDown(0.4);
    doc.fontSize(11);

    const signYStart = doc.y;
    doc.text("Owner Signature:", 50, signYStart);
    if (agreement.ownerSignatureUrl) {
      const rel = agreement.ownerSignatureUrl.replace(/^\/+/, "");
      const p = path.join(process.cwd(), rel);
      if (fs.existsSync(p)) {
        try {
          doc.image(p, 180, signYStart - 5, { width: 150 });
        } catch {}
      } else {
        doc.text("Not provided", 180, signYStart);
      }
    } else {
      doc.text("Not provided", 180, signYStart);
    }

    doc.moveDown(3);
    const signY2 = doc.y;
    doc.text("Tenant Signature:", 50, signY2);
    if (agreement.tenantSignatureUrl) {
      const rel = agreement.tenantSignatureUrl.replace(/^\/+/, "");
      const p = path.join(process.cwd(), rel);
      if (fs.existsSync(p)) {
        try {
          doc.image(p, 180, signY2 - 5, { width: 150 });
        } catch {}
      } else {
        doc.text("Not provided", 180, signY2);
      }
    } else {
      doc.text("Not provided", 180, signY2);
    }

    doc.moveDown(1);

    doc.fontSize(10).fillColor("#6b7280").text(
      "Generated by AafnoGhar. This PDF is a system-generated document.",
      { align: "center" }
    );

    drawStamp(doc, {
      text: "AafnoGhar Official",
      tagline: "Digital agreement",
    });

    doc.end();
  } catch (err) {
    console.error("PDF error:", err.message);
    res.status(500).json({ message: "Server error" });
  }
};

export { generateAgreementPdf };
